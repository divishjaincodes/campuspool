import { User, Ride, Booking, Message, Conversation, SafetyReport } from '../../types';

export const mapProfileToUser = (row: any): User => ({
  id: row.id,
  fullName: row.full_name || 'Student',
  email: row.email || '',
  avatarUrl: row.avatar_url || 'https://images.unsplash.com/photo-1534528741775-53994a69daeb?w=150&auto=format&fit=crop&q=80',
  college: row.college || 'VIT Bhopal University',
  regNumber: row.reg_number,
  gender: row.gender || 'undisclosed',
  phone: row.phone,
  bio: row.bio,
  vehicle: row.vehicle,
  isSuspended: row.is_suspended || false,
  verificationStatus: row.verification_status || 'verified',
  role: row.role || 'student',
  createdAt: row.created_at || new Date().toISOString(),
});

export const mapRideFromDb = (row: any): Ride => ({
  id: row.id,
  creatorId: row.creator_id,
  creator: row.creator ? mapProfileToUser(row.creator) : undefined,
  origin: row.origin,
  destination: row.destination,
  intermediateStops: row.intermediate_stops || [],
  departureDate: row.departure_date,
  departureTime: row.departure_time ? row.departure_time.substring(0, 5) : '08:00',
  estimatedDuration: row.estimated_duration,
  vehicleType: row.vehicle_type || 'Car',
  vehicleModel: row.vehicle_model,
  totalCapacity: Number(row.total_capacity) || 4,
  seatsOffered: Number(row.seats_offered) || 3,
  seatsRemaining: Number(row.seats_remaining) ?? Number(row.seats_offered) ?? 3,
  pricingType: row.pricing_type || 'fixed',
  pricePerSeat: Number(row.price_per_seat) || 0,
  totalTripCost: row.total_trip_cost ? Number(row.total_trip_cost) : undefined,
  contributingPassengersCount: row.contributing_passengers_count ? Number(row.contributing_passengers_count) : undefined,
  genderPreference: row.gender_preference || 'everyone',
  luggageAllowance: row.luggage_allowance || 'medium',
  acAvailable: row.ac_available ?? true,
  smokingAllowed: row.smoking_allowed ?? false,
  notes: row.notes,
  status: row.status || 'open',
  createdAt: row.created_at || new Date().toISOString(),
});

export const mapBookingFromDb = (row: any): Booking => ({
  id: row.id,
  rideId: row.ride_id,
  ride: row.ride ? mapRideFromDb(row.ride) : undefined,
  passengerId: row.passenger_id,
  passenger: row.passenger ? mapProfileToUser(row.passenger) : undefined,
  seatsBooked: Number(row.seats_booked) || 1,
  totalContribution: Number(row.total_contribution) || 0,
  status: row.status || 'confirmed',
  message: row.message,
  createdAt: row.created_at || new Date().toISOString(),
});
